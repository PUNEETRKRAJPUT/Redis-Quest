  balls.forEach((b, i) => { b.id = i + 1; w(row([b.id, b.match, b.innings, b.over, b.ball, b.batter, b.bowler, b.runs, b.extras, b.extraType, bool(b.wicket), b.wicketType, iso(b.at)])); });
