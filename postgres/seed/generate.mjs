for (let ui = 0; ui < users.length; ui++) {
  const u = users[ui];
  const k = frng.int(8, 12);
  const mine = frng.shuffle(completed.slice()).slice(0, k).sort((a, b) => a.n - b.n);
  for (const m of mine) {
    const teamId = fantasyTeams.length + 1;
    const createdAt = m.startsAt - frng.int(10, 600) * 60000;
    fantasyTeams.push({ id: teamId, user: u.id, match: m.id, createdAt });
    const xi = xiByMatch.get(m.id);
    const chosen = [];
    for (const [pid, base] of STAR_BASE) {
      const playing = xi.has(pid);
      if (frng.chance(base + (playing ? 0.10 : -0.04))) chosen.push(pid);
    }
    const ws = pickWeights.get(m.id).slice();
    while (chosen.length < 11) {
      const idx = frng.weighted(ws.map((_, i) => i), ws);
      ws[idx] = 0; chosen.push(others[idx].id);
    }
    // captain and vice: stars are the obvious captaincy picks, otherwise a high-fame pick.
    const byFame = chosen.slice().sort((a, b) => playerById.get(b).fame - playerById.get(a).fame);
    const cap = frng.chance(0.6) ? byFame[0] : frng.pick(chosen);
    let vice = frng.chance(0.6) ? byFame[1] : frng.pick(chosen);
    if (vice === cap) vice = chosen.find((c) => c !== cap);
    ftpRows.push({ team: teamId, chosen, cap, vice });
    // enter exactly one eligible contest for this match
    const scope = frng.weighted(['open', 'college', 'hostel'], [0.6, 0.25, 0.15]);
    const contest = scope === 'open' ? contestKey.get(`${m.id}|open|`) : scope === 'college' ? contestKey.get(`${m.id}|college|${u.college}`) : contestKey.get(`${m.id}|hostel|${u.hostel}`);
    let points = 0;
    for (const pid of chosen) points += pts(m.id, pid) * (pid === cap ? 2 : pid === vice ? 1.5 : 1);
    entries.push({ contest: contest.id, user: u.id, team: teamId, points: Math.round(points * 10) / 10 });
    if (contest.fee > 0) {
      txns.push({ user: u.id, delta: -contest.fee, reason: 'contest_entry', ref: `contest:${contest.id}`, at: createdAt + 60000 });
      balance.set(u.id, balance.get(u.id) - contest.fee);
    }
  }
}
txns.sort((a, b) => a.at - b.at || (a.user < b.user ? -1 : a.user > b.user ? 1 : 0));

copy('fantasy_teams', ['id', 'user_id', 'match_id', 'created_at'], () => {
  for (const f of fantasyTeams) w(row([f.id, f.user, f.match, iso(f.createdAt)]));
});
copy('fantasy_team_players', ['fantasy_team_id', 'player_id', 'is_captain', 'is_vice'], () => {
  for (const r of ftpRows) for (const pid of r.chosen) w(`${r.team}\t${pid}\t${pid === r.cap ? 't' : 'f'}\t${pid === r.vice ? 't' : 'f'}\n`);
});
copy('contest_entries', ['id', 'contest_id', 'user_id', 'fantasy_team_id', 'points'], () => {
  entries.forEach((e, i) => w(row([i + 1, e.contest, e.user, e.team, e.points])));
});
copy('wallet_transactions', ['id', 'user_id', 'delta', 'reason', 'ref', 'created_at'], () => {
  txns.forEach((t, i) => w(row([i + 1, t.user, t.delta, t.reason, t.ref, iso(t.at)])));
});
copy('wallets', ['user_id', 'balance'], () => {
  for (const u of users) w(row([u.id, balance.get(u.id)]));
});

