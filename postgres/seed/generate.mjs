// Fantasy points per (match, player). MUST match player_stats() in 004-slow-by-design.sql:
// batting: runs + 1 per four + 2 per six, -2 for a duck (dismissed, 0 runs in the match);
// bowling: 25 per wicket (run outs excluded) + 1 per dot ball.
{
  const bat = new Map(), bowl = new Map();
  for (const b of balls) {
    if (b.match > 'm-040') continue;
    const kb = `${b.match}|${b.batter}`;
    const s = bat.get(kb) || { runs: 0, fours: 0, sixes: 0, out: false };
    s.runs += b.runs; if (b.runs === 4) s.fours++; if (b.runs === 6) s.sixes++; if (b.wicket) s.out = true;
    bat.set(kb, s);
    const kw = `${b.match}|${b.bowler}`;
    const q = bowl.get(kw) || { wk: 0, dots: 0 };
    if (b.wicket && b.wicketType !== 'run out') q.wk++;
    if (b.runs === 0 && b.extraType === null && !b.wicket) q.dots++;
    bowl.set(kw, q);
  }
  for (const [k, s] of bat) playerMatchPoints.set(k, (playerMatchPoints.get(k) || 0) + s.runs + s.fours + 2 * s.sixes - (s.out && s.runs === 0 ? 2 : 0));
  for (const [k, q] of bowl) playerMatchPoints.set(k, (playerMatchPoints.get(k) || 0) + 25 * q.wk + q.dots);
}
const pts = (matchId, pid) => playerMatchPoints.get(`${matchId}|${pid}`) || 0;

