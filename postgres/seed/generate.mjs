// ================= BALL-BY-BALL SIMULATION
const squads = new Map(teams.map((t) => [t.id, players.filter((p) => p.team_id === t.id)]));
function pickXI(rng, squad) {
  const keepers = rng.shuffle(squad.filter((p) => p.role === 'keeper'));
  const batters = rng.shuffle(squad.filter((p) => p.role === 'batter'));
  const alls = rng.shuffle(squad.filter((p) => p.role === 'all-rounder'));
  const bowlers = rng.shuffle(squad.filter((p) => p.role === 'bowler'));
  const xi = [];
  const take = (arr, n) => { for (const p of arr) { if (n <= 0) break; if (!xi.includes(p)) { xi.push(p); n--; } } };
  take(squad.filter((p) => p.fame > 95), 1); // stars always play, they are the hot keys
  take(keepers, 1); take(batters, 4); take(alls, 3); take(bowlers, 3);
  const rest = rng.shuffle(squad.filter((p) => !xi.includes(p)));
  take(rest, 11 - xi.length);
  return xi.slice(0, 11);
}
const RUN_VALUES = [0, 1, 2, 3, 4, 6];
const BASE_W = [0.40, 0.34, 0.07, 0.01, 0.12, 0.06];
function runDist(target) { // exponential tilt so the expected runs per scoring ball equals target
  let lo = -3, hi = 3;
  const probs = (l) => { const ws = BASE_W.map((b, i) => b * Math.exp(l * RUN_VALUES[i])); const s = ws.reduce((x, y) => x + y, 0); return ws.map((x) => x / s); };
  const mean = (l) => probs(l).reduce((s, p, i) => s + p * RUN_VALUES[i], 0);
  for (let k = 0; k < 30; k++) { const mid = (lo + hi) / 2; if (mean(mid) < target) lo = mid; else hi = mid; }
  return probs((lo + hi) / 2);
}
const WICKET_TYPES = [['bowled', 0.28], ['caught', 0.50], ['lbw', 0.12], ['run out', 0.05], ['stumped', 0.05]];

const balls = []; // {match, innings, over, ball, batter, bowler, runs, extras, extraType, wicket, wicketType, at}
const playerMatchPoints = new Map(); // `${matchId}|${playerId}` -> fantasy points
const xiByMatch = new Map();

function simulateInnings(rng, m, innings, battingTeam, bowlingTeam, xiBat, xiBowl, target, maxLegal) {
  const order = xiBat.slice().sort((a, b) => {
    const wa = (a.role === 'bowler' ? -60 : 0) + a.bat_avg + (rng.next() - 0.5) * 18;
    const wb = (b.role === 'bowler' ? -60 : 0) + b.bat_avg + (rng.next() - 0.5) * 18;
    return wb - wa;
  });
  const bowlers = xiBowl.filter((p) => p.bowl_econ !== null);
  const oversBowled = new Map(bowlers.map((p) => [p.id, 0]));
  let striker = order[0], non = order[1], next = 2, wickets = 0, total = 0, legal = 0, prevBowler = null;
  let t = m.startsAt + (innings === 1 ? 0 : 75 * 60000);
  for (let over = 0; over < 20 && wickets < 10 && legal < maxLegal; over++) {
    const cand = bowlers.filter((p) => oversBowled.get(p.id) < 4 && p.id !== prevBowler);
    const bowler = cand.length ? rng.weighted(cand, cand.map((p) => 12 - p.bowl_econ + (p.role === 'bowler' ? 2 : 0) + 0.5)) : rng.pick(bowlers.filter((p) => oversBowled.get(p.id) < 4) .concat(bowlers));
    oversBowled.set(bowler.id, oversBowled.get(bowler.id) + 1);
    prevBowler = bowler.id;
    let ballNo = 0;
    while (ballNo < 6 && wickets < 10) {
      t += rng.int(25, 70) * 1000;
      const rpb = Math.max(0.35, (striker.strike_rate / 100) * Math.sqrt(bowler.bowl_econ / 8.2) * (over < 6 ? 0.9 : over >= 16 ? 1.25 : 1));
      const roll = rng.next();
      const rec = (runs, extras, extraType, wicket, wicketType) => balls.push({ match: m.id, innings, over, ball: ballNo + 1, batter: striker.id, bowler: bowler.id, runs, extras, extraType, wicket, wicketType, at: t });
      if (roll < 0.035) { rec(0, 1, 'wide', false, null); total += 1; continue; }
      if (roll < 0.043) { // no ball: free hit scoring, runs off the bat possible
        const r = rng.weighted(RUN_VALUES, runDist(rpb)); rec(r, 1, 'noball', false, null); total += 1 + r; if (r % 2 === 1) [striker, non] = [non, striker];
        if (target !== null && total > target) { return { total, wickets, legal }; } continue;
      }
      let extras = 0, extraType = null, runs = 0, wicket = false, wicketType = null;
      if (roll < 0.053) { extras = 1; extraType = rng.chance(0.5) ? 'bye' : 'legbye'; }
      else {
        const pw = Math.min(0.12, (rpb / Math.max(striker.bat_avg, 8)) * (over >= 16 ? 1.3 : 1) * (12 - Math.min(bowler.bowl_econ, 11)) / 5.5);
        if (rng.next() < pw) { wicket = true; wicketType = rng.weighted(WICKET_TYPES.map((x) => x[0]), WICKET_TYPES.map((x) => x[1])); }
        else runs = rng.weighted(RUN_VALUES, runDist(Math.max(0.4, rpb)));
      }
      ballNo++; legal++;
      rec(runs, extras, extraType, wicket, wicketType);
      total += runs + extras;
      if (wicket) { wickets++; if (next < order.length) striker = order[next++]; }
      else if ((runs + extras) % 2 === 1) [striker, non] = [non, striker];
      if (target !== null && total > target) return { total, wickets, legal };
    }
    [striker, non] = [non, striker];
  }
  return { total, wickets, legal };
}

const srng = stream('season');
for (const m of matches) {
  if (m.status === 'scheduled') continue;
  const homeXI = pickXI(srng, squads.get(m.home));
  const awayXI = pickXI(srng, squads.get(m.away));
  xiByMatch.set(m.id, new Set([...homeXI, ...awayXI].map((p) => p.id)));
  const tossBatFirstHome = srng.chance(0.5);
  const [firstXI, secondXI, firstTeam, secondTeam] = tossBatFirstHome ? [homeXI, awayXI, m.home, m.away] : [awayXI, homeXI, m.away, m.home];
  if (m.status === 'completed') {
    const i1 = simulateInnings(srng, m, 1, firstTeam, secondTeam, firstXI, secondXI, null, 120);
    simulateInnings(srng, m, 2, secondTeam, firstTeam, secondXI, firstXI, i1.total, 120);
  } else {
    // live: first innings part-way through (m-041 at over 11, m-042 at over 4), so the ticker has something to read
    simulateInnings(srng, m, 1, firstTeam, secondTeam, firstXI, secondXI, null, m.n === 41 ? 66 : 25);
  }
}
